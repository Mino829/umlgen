#!/usr/bin/env python3
"""Generate Homebrew/Scoop definitions from one exact published stable release."""

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import urllib.error
import urllib.request


ROOT = Path(__file__).resolve().parents[1]
REPOSITORY = "Mino829/umlgen"
HOMEPAGE = f"https://github.com/{REPOSITORY}"
ARCHIVES = (
    "umlgen-darwin-amd64.tar.gz",
    "umlgen-darwin-arm64.tar.gz",
    "umlgen-linux-amd64.tar.gz",
    "umlgen-windows-amd64.zip",
)
PACKAGE_ARCHIVES = tuple(name for name in ARCHIVES if "linux" not in name)
MANIFEST = "SHA256SUMS.txt"


def stable_version(value):
    if not re.fullmatch(r"v?(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)", value, re.ASCII):
        raise ValueError("version must be an exact stable X.Y.Z or vX.Y.Z; prereleases/build metadata are unsupported")
    return value.removeprefix("v")


def parse_checksums(text):
    hashes = {}
    for number, line in enumerate(text.splitlines(), 1):
        match = re.fullmatch(r"([0-9a-fA-F]{64}) [ *]([A-Za-z0-9.-]+)", line, re.ASCII)
        if not match:
            raise ValueError(f"invalid SHA-256 manifest line {number}")
        digest, name = match.groups()
        if name not in ARCHIVES:
            raise ValueError(f"unexpected checksum filename: {name}")
        if name in hashes:
            raise ValueError(f"duplicate checksum: {name}")
        hashes[name] = digest.lower()
    missing = set(ARCHIVES) - hashes.keys()
    if missing:
        raise ValueError(f"missing checksums: {', '.join(sorted(missing))}")
    return hashes


def validate_release(release, version):
    tag = f"v{version}"
    if release.get("tag_name") != tag or release.get("draft") is not False or release.get("prerelease") is not False:
        raise ValueError(f"{tag} must be an already published, non-draft stable release")
    assets = {}
    for asset in release.get("assets", []):
        name = asset.get("name")
        if not isinstance(name, str) or name in assets:
            raise ValueError(f"invalid or duplicate release asset: {name}")
        assets[name] = asset
    for name in (*ARCHIVES, MANIFEST):
        expected = f"{HOMEPAGE}/releases/download/{tag}/{name}"
        if name not in assets:
            raise ValueError(f"missing release asset: {name}")
        if assets[name].get("browser_download_url") != expected:
            raise ValueError(f"unexpected release asset URL: {name}")
    return assets


def request(url, *, api=False):
    headers = {"User-Agent": "umlgen-package-manager-update"}
    if api:
        headers["Accept"] = "application/vnd.github+json"
        token = os.environ.get("GH_TOKEN") or os.environ.get("GITHUB_TOKEN")
        if token:
            headers["Authorization"] = f"Bearer {token}"
    return urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=60)


def verify_digest(asset, actual, expected):
    if actual != expected:
        raise ValueError(f"SHA-256 mismatch for {asset['name']}")
    # Older GitHub releases may not have an API digest. If present, it must agree.
    recorded = asset.get("digest")
    if recorded is not None and recorded != f"sha256:{actual}":
        raise ValueError(f"GitHub API digest mismatch for {asset['name']}")


def released_checksums(version):
    with request(f"https://api.github.com/repos/{REPOSITORY}/releases/tags/v{version}", api=True) as response:
        assets = validate_release(json.load(response), version)
    with request(assets[MANIFEST]["browser_download_url"]) as response:
        data = response.read(65537)
    if len(data) > 65536:
        raise ValueError("SHA256SUMS.txt is too large")
    manifest_digest = hashlib.sha256(data).hexdigest()
    verify_digest(assets[MANIFEST], manifest_digest, manifest_digest)
    hashes = parse_checksums(data.decode("ascii"))
    # Verify the actual package bytes as well as the manifest before writing anything.
    for name in PACKAGE_ARCHIVES:
        digest = hashlib.sha256()
        with request(assets[name]["browser_download_url"]) as response:
            for block in iter(lambda: response.read(1024 * 1024), b""):
                digest.update(block)
        verify_digest(assets[name], digest.hexdigest(), hashes[name])
    return hashes


def definitions(version, hashes):
    base = f"{HOMEPAGE}/releases/download/v{version}"
    formula = f'''# Generated by scripts/update-package-managers.py; do not edit version/hashes by hand.
class Umlgen < Formula
  desc "Generate PlantUML diagrams from Java and Go source code"
  homepage "{HOMEPAGE}"
  version "{version}"
  license "MIT"

  depends_on :macos

  on_arm do
    url "{base}/umlgen-darwin-arm64.tar.gz"
    sha256 "{hashes['umlgen-darwin-arm64.tar.gz']}"
  end

  on_intel do
    url "{base}/umlgen-darwin-amd64.tar.gz"
    sha256 "{hashes['umlgen-darwin-amd64.tar.gz']}"
  end

  def install
    arch = Hardware::CPU.arm? ? "arm64" : "amd64"
    bin.install "umlgen-darwin-#{{arch}}" => "umlgen"
  end

  test do
    assert_match "umlgen version #{{version}}", shell_output("#{{bin}}/umlgen version")
    (testpath/"Sample.java").write("public class Sample {{ private String name; }}\\n")
    system bin/"umlgen", "class", testpath, "--output", testpath/"class.puml", "--quiet"
    diagram = (testpath/"class.puml").read
    assert_match "@startuml", diagram
    assert_match "Sample", diagram
    assert_match "@enduml", diagram
  end
end
'''
    manifest = {
        "##": "Generated by scripts/update-package-managers.py; do not edit version/hashes by hand.",
        "version": version,
        "description": "Generate PlantUML diagrams from Java and Go source code",
        "homepage": HOMEPAGE,
        "license": "MIT",
        "architecture": {
            "64bit": {
                "url": f"{base}/umlgen-windows-amd64.zip",
                "hash": hashes["umlgen-windows-amd64.zip"],
            },
        },
        "bin": [["umlgen-windows-amd64.exe", "umlgen"]],
        "notes": [
            "PlantUML is optional for SVG/PNG output; .puml generation needs no renderer.",
            "Java sequence/activity/state analysis requires a separate full JDK 17+ (java and javac on PATH).",
        ],
    }
    return {"Formula/umlgen.rb": formula, "bucket/umlgen.json": json.dumps(manifest, indent=4) + "\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", required=True, help="exact published stable release, e.g. v0.6.0")
    parser.add_argument("--output-dir", type=Path, default=ROOT)
    parser.add_argument("--check", action="store_true", help="fail instead of writing if definitions differ")
    args = parser.parse_args()
    try:
        version = stable_version(args.version)
        files = definitions(version, released_checksums(version))
        for name, text in files.items():
            destination = args.output_dir / name
            if args.check:
                if not destination.is_file() or destination.read_text(encoding="utf-8") != text:
                    raise ValueError(f"outdated package definition: {name}")
            else:
                destination.parent.mkdir(parents=True, exist_ok=True)
                destination.write_text(text, encoding="utf-8", newline="\n")
        print(f"{'Checked' if args.check else 'Generated'} Homebrew/Scoop definitions for v{version}")
    except (ValueError, OSError, urllib.error.URLError) as error:
        parser.exit(1, f"update-package-managers: {error}\n")


if __name__ == "__main__":
    main()
